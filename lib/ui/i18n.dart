import 'package:flutter/widgets.dart';

/// The app's language (founder, 26 Oct 2026): 'en' English, 'hi' Hindi, 'hi-en' Hinglish — the store's choice in Settings → Me & app,
/// read when the app starts and changed with one tap there. Text is written in English in the code and shown through [tr].
final appLang = ValueNotifier<String>('en');

/// Switches the language and redraws every screen at once (no restart, the open screens stay where they are).
void setAppLanguage(String code) {
  final c = _known(code);
  if (c == appLang.value) return;
  appLang.value = c;
  final root = WidgetsBinding.instance.rootElement;
  if (root == null) return;
  void redraw(Element e) {
    e.markNeedsBuild();
    e.visitChildren(redraw);
  }
  redraw(root);
}

String _known(String code) => code == 'hi' || code == 'hi-en' ? code : 'en';

/// [en] in the app's language; the English itself when that line has no translation yet.
String tr(String en) {
  final l = appLang.value;
  if (l == 'en') return en;
  final w = _words[en];
  return w == null ? en : (l == 'hi' ? w.$1 : w.$2);
}

